def main():
    import json
    items = json.load(open(os.path.join(ROOT, "items_registry", "items.json"),
                           encoding="utf-8"))["items"]
    ids = {i["id"] for i in items}
    missing = [k for k in RATIONALE if k not in ids]
    if missing:
        raise SystemExit("来由表含不存在的事项：%s" % missing)
    for item_id in sorted(RATIONALE):
        ledger.set_rationale(item_id, RATIONALE[item_id], author=AUTHOR)
    print("来由补录 %d 条完成" % len(RATIONALE))
    for item_id in sorted(LINES):
        ledger.set_line(item_id, LINES[item_id], author=AUTHOR)
    print("逻辑线归属 %d 条完成" % len(LINES))
    for item_id, targets in ENABLES.items():
        ledger.set_enables(item_id, targets, author=AUTHOR)
    print("启发种子 %d 条完成" % len(ENABLES))
    for item_id, deps in DEPENDS.items():
        ledger.set_depends(item_id, deps, author=AUTHOR)
    print("依赖补录 %d 条完成" % len(DEPENDS))


if __name__ == "__main__":
    main()
